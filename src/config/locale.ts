/**
 * ════════════════════════════════════════════════════════════════
 *  语言：只有一种 —— 约旦阿拉伯语
 * ════════════════════════════════════════════════════════════════
 *
 *  站点是约旦本地的夜间视频社区，访客只讲阿拉伯语。
 *  所以这里不再有语言切换：dir 永远是 rtl，lang 永远是 ar。
 *
 *  为什么把语言收成一个常量，而不是留个开关：
 *  只要开关还在，就总有一天会被点开，然后把整站切成另一种语言。
 *  这个站不需要那个风险。
 */

/** <html lang="…"> 与服务端 / 页签用的语言标记 */
export const HTML_LANG = 'ar'

/** 书写方向。整站的镜像、箭头方向、间距方向都由它决定 */
export const DIR = 'rtl' as const

/**
 * Intl 用的地区标记：约旦阿拉伯语 + 拉丁数字。
 *
 * 为什么强制拉丁数字（u-nu-latn）：
 * 阿拉伯-印度数字（١٢٣٤）在手机状态栏、点赞数、距离之间风格不统一，
 * 而约旦的社交类应用普遍用 0-9。统一成拉丁数字，视觉更稳。
 */
export const INTL_LOCALE = 'ar-JO-u-nu-latn'

/** 分享卡片（og:locale）用的地区标记 */
export const OG_LOCALE = 'ar_JO'
